def run(text, *flags):
    with tempfile.TemporaryDirectory() as tmp:
        target = Path(tmp) / "spec.md"
        target.write_text(text, encoding="utf-8")
        done = subprocess.run(
            [sys.executable, str(CHECK), *flags, str(target)], capture_output=True, text=True
        )
    return done.returncode, done.stdout + done.stderr


def section(output, level):
    lines, inside = [], False
    for line in output.splitlines():
        if line.startswith(("오류 ", "빈칸 ", "미정 ", "요약:")):
            inside = line.startswith(level + " ")
            continue
        if inside:
            lines.append(line)
    return "\n".join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit("쓰는 법: python3 appspec_selftest.py 예시파일.md")
    base = Path(sys.argv[1]).read_text(encoding="utf-8")
    failed = 0

    code, output = run(base, "--strict")
    clean = code == 0 and not any(section(output, level) for level in ("오류", "빈칸", "미정"))
    print(("통과" if clean else "실패") + "  원본은 아무것도 걸리지 않는다")
    if not clean:
        failed += 1
        print(output)

    for name, old, new, level, expect, exit_code in CASES:
        if old is None:
            text = base + new
        else:
            edits = old if isinstance(old, tuple) else ((old, new),)
            if any(before not in base for before, _ in edits):
                print(f"실패  {name}: 바꿀 글을 원본에서 찾지 못했다")
                failed += 1
                continue
            text = base
            for before, after in edits:
                text = text.replace(before, after, 1)
        code, output = run(text)
        ok = expect in section(output, level) and code == exit_code
        strict_note = ""
        if ok and level in ("빈칸", "미정") and exit_code == 0:
            strict_code, _ = run(text, "--strict")
            ok = strict_code == 1
            strict_note = " (--strict 에서는 실패)"
        print(("통과" if ok else "실패") + f"  {name}: {level}{strict_note}")
        if not ok:
            failed += 1
            print(f"      기대한 글: {expect} / 종료 코드 {exit_code}, 실제 {code}")
            print("      " + output.replace("\n", "\n      "))

    total = len(CASES) + 1
    print(f"\n{total - failed}/{total} 통과")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
